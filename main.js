// IF — ЗАДАНИЕ 1
//
// Запросить у пользователя число и определить, оно
// положительное, отрицательное или ноль.
//
// Тут сначала через prompt получаю число от пользователя.
// Number нужен потому что prompt возвращает строку, а мне надо
// нормально сравнивать именно число.
//
// Дальше обычный if. Если число больше 0 - положительное,
// если меньше 0 - отрицательное. Ну и если ни то ни другое,
// значит остается только 0.

let number = Number(prompt('IF - Задание 1. Введите число:'))

if (number > 0) {
	alert('Число положительное')
} else if (number < 0) {
	alert('Число отрицательное')
} else {
	alert('Число равно нулю')
}

// IF — ЗАДАНИЕ 2
//
// Запросить у пользователя его возраст и проверить
// корректность введенных данных (0-120 лет).
//
// Тут спрашиваю возраст и проверяю сразу два условия.
// Возраст должен быть больше или равен 0 И при этом меньше
// или равен 120.
//
// && как раз означает "И", то есть оба условия должны
// выполняться одновременно.

let age = Number(prompt('IF - Задание 2. Введите ваш возраст:'))

if (age >= 0 && age <= 120) {
	alert('Возраст введен корректно')
} else {
	alert('Возраст введен некорректно')
}

// IF — ЗАДАНИЕ 3
//
// Запросить у пользователя число и вывести его модуль
// (|7| = 7, |-7| = 7).
//
// Вообще в JS есть Math.abs(), который сразу может получить
// модуль числа, но тут задание именно на IF, поэтому делаю
// через условие.
//
// Если число меньше нуля, просто меняю ему знак.
// Если оно уже положительное или 0, вообще ничего делать
// не надо, просто потом вывожу его.

let moduleNumber = Number(prompt('IF - Задание 3. Введите число:'))

if (moduleNumber < 0) {
	moduleNumber = -moduleNumber
}

alert('Модуль числа: ' + moduleNumber)

// IF — ЗАДАНИЕ 4
//
// Запросить у пользователя время (часы, минуты, секунды)
// и проверить корректность введенных данных.
//
// Тут отдельно спрашиваю часы, минуты и секунды.
//
// У нормального времени:
// часы от 0 до 23,
// минуты от 0 до 59,
// секунды от 0 до 59.
//
// Все эти проверки соединяю через &&, потому что время
// корректное только если вообще ВСЕ значения нормальные.

let hours = Number(prompt('IF - Задание 4. Введите часы:'))
let minutes = Number(prompt('Введите минуты:'))
let seconds = Number(prompt('Введите секунды:'))

if (
	hours >= 0 &&
	hours <= 23 &&
	minutes >= 0 &&
	minutes <= 59 &&
	seconds >= 0 &&
	seconds <= 59
) {
	alert('Время введено корректно')
} else {
	alert('Время введено некорректно')
}

// IF — ЗАДАНИЕ 5
//
// Запросить координаты точки (x, y) и определить номер
// четверти, в которую попала эта точка. Необходимо учесть
// случаи попадания точки на оси X или Y или в начало координат.
//
// Тут получаю x и y, а потом уже смотрю на их знаки.
//
// I четверть:   x плюс,  y плюс
// II четверть:  x минус, y плюс
// III четверть: x минус, y минус
// IV четверть:  x плюс,  y минус
//
// Еще отдельно надо проверить нули. Если оба 0 - это начало
// координат. Если только x = 0, значит точка на оси Y.
// В оставшемся случае y = 0, значит точка на оси X.

let x = Number(prompt('IF - Задание 5. Введите координату X:'))
let y = Number(prompt('Введите координату Y:'))

if (x > 0 && y > 0) {
	alert('Точка находится в I четверти')
} else if (x < 0 && y > 0) {
	alert('Точка находится во II четверти')
} else if (x < 0 && y < 0) {
	alert('Точка находится в III четверти')
} else if (x > 0 && y < 0) {
	alert('Точка находится в IV четверти')
} else if (x === 0 && y === 0) {
	alert('Точка находится в начале координат')
} else if (x === 0) {
	alert('Точка находится на оси Y')
} else {
	alert('Точка находится на оси X')
}

// SWITCH — ЗАДАНИЕ 1
//
// Запросить у пользователя номер месяца и вывести на экран
// его название.
//
// Тут switch удобнее чем писать 12 if'ов.
// В switch передаю номер месяца, а каждый case это один
// возможный вариант.
//
// Например если month равен 3, сработает case 3 и выведется
// "Март".
//
// break нужен чтобы после найденного варианта switch
// остановился и не пошел выполнять следующие case.
//
// default сработает если ввели вообще не число от 1 до 12.

let month = Number(prompt('SWITCH - Задание 1. Введите номер месяца (1-12):'))

switch (month) {
	case 1:
		alert('Январь')
		break

	case 2:
		alert('Февраль')
		break

	case 3:
		alert('Март')
		break

	case 4:
		alert('Апрель')
		break

	case 5:
		alert('Май')
		break

	case 6:
		alert('Июнь')
		break

	case 7:
		alert('Июль')
		break

	case 8:
		alert('Август')
		break

	case 9:
		alert('Сентябрь')
		break

	case 10:
		alert('Октябрь')
		break

	case 11:
		alert('Ноябрь')
		break

	case 12:
		alert('Декабрь')
		break

	default:
		alert('Такого месяца не существует')
}

// SWITCH — ЗАДАНИЕ 2
//
// Реализовать калькулятор. Пользователь вводит 2 числа и
// знак (+ - * /). В зависимости от введенного знака решить
// пример и вывести результат.
//
// Тут сначала получаю два числа, а потом отдельно operation,
// то есть какой знак ввел пользователь.
//
// Дальше switch смотрит на этот знак.
// Если +, складываю, если -, вычитаю и так далее.
//
// Для деления еще сделал проверку на 0, потому что на ноль
// делить нельзя.
//
// default нужен если пользователь вместо + - * /
// ввел вообще что-то другое.

let firstNumber = Number(prompt('SWITCH - Задание 2. Введите первое число:'))
let secondNumber = Number(prompt('Введите второе число:'))
let operation = prompt('Введите знак операции (+, -, *, /):')

let result

switch (operation) {
	case '+':
		result = firstNumber + secondNumber
		alert('Результат: ' + result)
		break

	case '-':
		result = firstNumber - secondNumber
		alert('Результат: ' + result)
		break

	case '*':
		result = firstNumber * secondNumber
		alert('Результат: ' + result)
		break

	case '/':
		if (secondNumber !== 0) {
			result = firstNumber / secondNumber
			alert('Результат: ' + result)
		} else {
			alert('На ноль делить нельзя')
		}
		break

	default:
		alert('Неизвестная операция')
}

// ТЕРНАРНЫЙ ОПЕРАТОР — ЗАДАНИЕ 1
//
// Запросить 2 числа и вывести большее из них.
//
// Тут уже по заданию надо использовать тернарный оператор.
// По сути это короткая запись простого if else.
//
// До ? идет условие num1 > num2.
// После ? пишется что взять если условие true.
// После : что взять если условие false.
//
// То есть если num1 больше - записываем num1,
// иначе записываем num2.

let num1 = Number(
	prompt('Тернарный оператор - Задание 1. Введите первое число:'),
)
let num2 = Number(prompt('Введите второе число:'))

let maxNumber = num1 > num2 ? num1 : num2

alert('Большее число: ' + maxNumber)

// ТЕРНАРНЫЙ ОПЕРАТОР — ЗАДАНИЕ 2
//
// Запросить 1 число и проверить, оно кратно 5 или нет.
//
// Тут через % получаю остаток от деления числа на 5.
// Если остаток 0, значит число делится на 5 полностью,
// соответственно оно кратно 5.
//
// Через тернарный оператор сразу выбираю какой текст
// записать в multipleResult.

let multipleNumber = Number(
	prompt('Тернарный оператор - Задание 2. Введите число:'),
)

let multipleResult =
	multipleNumber % 5 === 0 ? 'Число кратно 5' : 'Число не кратно 5'

alert(multipleResult)

// ТЕРНАРНЫЙ ОПЕРАТОР — ЗАДАНИЕ 3
//
// Запросить у пользователя название планеты. Если пользователь
// ввел "Земля" или "земля", то вывести "Привет, землянин!",
// в остальных случаях вывести "Привет, инопланетянин!".
//
// Тут получаю название планеты как обычную строку.
// Number тут уже естественно не нужен, потому что мы работаем
// с текстом.
//
// Через || проверяю сразу два варианта: "Земля" ИЛИ "земля".
// || как раз означает логическое "ИЛИ".
//
// Если хотя бы один вариант совпал - пользователь землянин.
// Если нет - инопланетянин.

let planet = prompt('Тернарный оператор - Задание 3. Введите название планеты:')

let greeting =
	planet === 'Земля' || planet === 'земля'
		? 'Привет, землянин!'
		: 'Привет, инопланетянин!'

alert(greeting)
